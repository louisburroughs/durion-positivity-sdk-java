#!/usr/bin/env python3
"""Generate <module>/src/main/java/.../OperationRequirements.java for every SDK module.

Reads each module's pom.xml (inputSpec + apiPackage) and its backend OpenAPI spec, and
emits an immutable Map<String, OperationRequirement> keyed by operationId.

Per operation:
  x-required-permissions      -> every permission code the authorization expression names
                                 (the single value AUTHENTICATED = any signed-in caller)
  x-required-permissions-all  -> subset of those codes that are each required (optional)
  allOf = -all list; anyOf = codes minus allOf minus AUTHENTICATED; authenticated = codes == [AUTHENTICATED]
An operation with no x-required-permissions is left OUT (unknown -> consumers fail closed).

Usage: scripts/generate-operation-requirements.py [--root DIR] [--module sdk-java-x ...]
Output is deterministic (sorted by operationId); rerun is a no-op when nothing changed.
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

SENTINEL = "AUTHENTICATED"
HTTP_METHODS = {"get", "put", "post", "delete", "options", "head", "patch", "trace"}
CLASS_NAME = "OperationRequirements"


def requirement_for(op):
    """Return (anyOf, allOf, authenticated) or None when the operation has no extension."""
    perms = op.get("x-required-permissions")
    if perms is None:
        return None
    perms = [str(p) for p in perms]
    all_of = sorted({str(p) for p in (op.get("x-required-permissions-all") or [])} - {SENTINEL})
    authenticated = perms == [SENTINEL]
    any_of = sorted({p for p in perms if p != SENTINEL} - set(all_of))
    return any_of, all_of, authenticated


def collect(spec):
    """Return (requirements by operationId, operation count, operations lacking the extension)."""
    reqs, total, missing = {}, 0, []
    for path, item in (spec.get("paths") or {}).items():
        for method, op in (item or {}).items():
            if method not in HTTP_METHODS or not isinstance(op, dict):
                continue
            total += 1
            op_id = op.get("operationId")
            if not op_id:
                missing.append(f"{method.upper()} {path} (no operationId)")
                continue
            req = requirement_for(op)
            if req is None:
                missing.append(op_id)
            else:
                reqs[op_id] = req
    return reqs, total, missing


def java_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def java_list(items):
    return "List.of(" + ", ".join(java_str(i) for i in items) + ")" if items else "List.of()"


def render(package, reqs):
    lines = [
        f"package {package};",
        "",
        "import com.positivity.sdk.core.OperationRequirement;",
        "import java.util.Collections;",
        "import java.util.LinkedHashMap;",
        "import java.util.List;",
        "import java.util.Map;",
        "",
        "/**",
        " * GENERATED by scripts/generate-operation-requirements.py from the backend OpenAPI spec. Do not edit.",
        " *",
        " * <p>Maps operationId to the permissions the backend requires for it. An operation missing from",
        " * the map has unknown requirements: treat it as denied (fail closed).",
        " */",
        f"public final class {CLASS_NAME} {{",
        "",
        "    public static final Map<String, OperationRequirement> BY_OPERATION_ID;",
        "",
        "    static {",
        "        Map<String, OperationRequirement> m = new LinkedHashMap<>();",
    ]
    for op_id in sorted(reqs):
        any_of, all_of, auth = reqs[op_id]
        lines.append(
            f"        m.put({java_str(op_id)}, new OperationRequirement("
            f"{java_list(any_of)}, {java_list(all_of)}, {'true' if auth else 'false'}));"
        )
    lines += [
        "        BY_OPERATION_ID = Collections.unmodifiableMap(m);",
        "    }",
        "",
        f"    private {CLASS_NAME}() {{}}",
        "}",
        "",
    ]
    return "\n".join(lines)


def module_info(pom):
    """Return (inputSpec path, apiPackage) from a module pom, or None for a non-generating module."""
    text = pom.read_text()
    spec = re.search(r"<inputSpec>(.*?)</inputSpec>", text)
    api = re.search(r"<apiPackage>(.*?)</apiPackage>", text)
    if not spec or not api:
        return None
    path = spec.group(1).replace("${project.basedir}", str(pom.parent))
    return Path(path).resolve(), api.group(1).removesuffix(".api")


def generate(module_dir, out=None):
    info = module_info(module_dir / "pom.xml")
    if info is None:
        return None
    spec_path, package = info
    with open(spec_path) as f:
        spec = yaml.load(f, Loader=getattr(yaml, "CSafeLoader", yaml.SafeLoader))
    reqs, total, missing = collect(spec)
    target = module_dir / "src/main/java" / package.replace(".", "/") / f"{CLASS_NAME}.java"
    content = render(package, reqs)
    if not target.exists() or target.read_text() != content:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    return {
        "module": module_dir.name,
        "operations": total,
        "mapped": len(reqs),
        "authenticated": sum(1 for r in reqs.values() if r[2]),
        "with_all": sum(1 for r in reqs.values() if r[1]),
        "missing": missing,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--module", action="append", help="limit to these module directory names")
    args = ap.parse_args()
    root = Path(args.root)
    mods = sorted(p for p in root.glob("sdk-java-*") if (p / "pom.xml").exists())
    if args.module:
        mods = [m for m in mods if m.name in args.module]
    totals = dict(operations=0, mapped=0, authenticated=0, with_all=0)
    n = 0
    for m in mods:
        r = generate(m)
        if r is None:
            continue
        n += 1
        for k in totals:
            totals[k] += r[k]
        print(f"{r['module']}: {r['mapped']}/{r['operations']} mapped, {r['authenticated']} authenticated-only, "
              f"{len(r['missing'])} without extension")
    print(f"TOTAL modules={n} " + " ".join(f"{k}={v}" for k, v in totals.items())
          + f" without_extension={totals['operations'] - totals['mapped']}")


if __name__ == "__main__":
    sys.exit(main())
